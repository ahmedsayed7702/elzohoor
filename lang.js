function setLang(lang) {
  document.documentElement.lang = lang;
  document.documentElement.dir = lang === "ar" ? "rtl" : "ltr";
  document.querySelectorAll("[data-i18n]").forEach(el => {
    const key = el.getAttribute("data-i18n");
    if (el.tagName === "INPUT" || el.tagName === "TEXTAREA" || el.tagName === "BUTTON") {
      el.value = translations[lang][key] || "";
    } else {
      el.innerHTML = translations[lang][key] || "";
    }
  });

  // تحديث المنتجات إذا كانت الصفحة تحتوي على دالة showCategory
  if (typeof showCategory === "function") {
    // حدد الزر النشط أو الافتراضي
    const activeBtn = document.querySelector('.product-buttons button.active');
    if (activeBtn) {
      showCategory(activeBtn.dataset.category);
    } else if (document.querySelector('.product-buttons button[data-category="import"]')) {
      showCategory('import');
    }
  }

  localStorage.setItem("lang", lang);
  var sel = document.getElementById('lang-select');
  if(sel) sel.value = lang;
}

window.addEventListener("DOMContentLoaded", () => {
  const savedLang = localStorage.getItem("lang") || "en";
  setLang(savedLang);
  var sel = document.getElementById('lang-select');
  if(sel) sel.value = savedLang;
  if(sel) sel.onchange = function() { setLang(this.value); };
});

